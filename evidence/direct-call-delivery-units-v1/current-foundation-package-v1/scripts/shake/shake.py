#!/usr/bin/env python3
"""Remove unused imports from FV, FVTest and Corpus (the import analysis of `lake shake`, for plain
non-`module` files, which `lake shake` itself refuses).

usage: scripts/shake/shake.py [--facts FILE] [--ignore-pr N] [--dry-run] [--report FILE]

Run from the worktree root after building every module (`scripts/lake-serial-build.py FV FVTest
Corpus`): `scripts/shake/Facts.lean` loads all .olean files and records, per module, the modules
its constants mention, the modules the elaborator recorded as extra dependencies (notations,
macros, elaborators, attributes, simp sets, ...), the modules of the global names its macros
quote, and the modules that applied attributes to the constants it uses. Further needs the .olean
files do not record (all kept if they were in the old closure): the modules declaring the syntax
a file parses (`declared_atoms`), the modules adding lemmas to a custom simp set the file uses
(`simp_need`), a module registering every namespace the file opens (`open_requirements`). This script then rewrites the import lines like `lake shake --keep-implied`:

* an import is kept if a module it provides (itself or transitively) is needed and not already
  provided by another needed import, or if it is implied by the kept imports anyway (keeping it
  does not change the import graph, and saves edits);
* every other import is removed; a module whose needs are no longer reachable gets the direct
  import it needs (for Lean/Std modules: the coarsest Lean/Std import its old closure had);
* modules are visited in import order, so an importer sees its imports' new import lists.

Never edited (their import lines are kept as they are):
* imports marked `-- shake: keep`, all imports of a file containing `shake: keep-all` or listed as
  `keep: PATH` in scripts/shake/generated.txt;
* imports of Lean/Std/Init modules (they are never rebuilt);
* imports of submodules (`FV.Arm` importing `FV.Arm.X`, umbrella files) and files without
  constants (umbrellas, `#eval`/`example`-only tests);
* generated files (their header names an in-repo generator: `GENERATED by `X``, `Generated by
  `X``, `Regenerate: `...``), unless scripts/shake/generated.txt lists the generator: those
  generators emit the imports this script leaves, so their files are edited like the others;
* files touched by an open, non-draft pull request (unless --ignore-pr N names it), so in-flight work does
  not conflict.
These "frozen" files, and the Lean files outside FV/FVTest/Corpus that import them (the axiom
audits scripts/audit/*.lean, scripts/rust-clif/*.lean, float-spec/defs-hash.lean, and the built
crate-proofs package), keep their imports; a removal elsewhere that would drop one of their needs
from their import closure is not made.

`open X` fails unless an imported module registers the namespace X, which the .olean files do not
record as a use: the script keeps, for every `open`, a module registering it (the lowest one of
the old closure) in the new closure. `example`, `#guard`, `#eval`, `#check` and `#print`
are not in the .olean either: modules with them are re-elaborated as shadow copies in which they
are declarations (`shadow_text`), and the copies' needs count too. Imports that matter in other
ways the .olean files do not record must be marked `-- shake: keep`; the build gate finds them.

Regenerating on a fresh main: build everything, run this script, build again (the gate).
"""
