ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
LIBS = {"FV": "FV", "FVTest": "FVTest", "Corpus": "corpus/dsl/Corpus"}
GENERATED = re.compile(r"(?:GENERATED by|Generated by|Regenerate:)\s*`([^`]+)`")


def generator_of(text, rel):
    """The in-repo generator (a file or directory path) a generated file names in its header
    (`GENERATED by `X``, `-- Generated by `X``, `Regenerate: `... X ...``), or None."""
    for mo in GENERATED.finditer(text[:4000]):
        toks = [t for t in re.split(r"[\s>]+", mo.group(1)) if "/" in t and (ROOT / t).exists()]
        if toks:
            return None if toks[0] == rel else toks[0]   # (the generator itself: None)
    return None
UMBRELLA = 3


def internal(m):
    return m.split(".")[0] in LIBS


def mod_path(m):
    head, *rest = m.split(".")
    return ROOT / LIBS[head] / pathlib.Path(*rest[:-1]) / (rest[-1] + ".lean") if rest else None


def all_modules():
    mods = []
    for head, d in LIBS.items():
        for p in sorted((ROOT / d).rglob("*.lean")):
            rel = p.relative_to(ROOT / d).with_suffix("")
            mods.append(".".join((head,) + rel.parts))
    return mods


def parse_header(text):
    """(import lines [(line index, module, keep?)], index after the last import line)."""
    i, n = 0, len(text)
    imports = []
    while True:
        while i < n and text[i].isspace():
            i += 1
        if text.startswith("--", i):
            i = text.find("\n", i) if "\n" in text[i:] else n
            continue
        if text.startswith("/-", i) and not text.startswith("/-!", i) and not text.startswith("/--", i):
            depth, i = 1, i + 2
            while i < n and depth:
                if text.startswith("/-", i):
                    depth, i = depth + 1, i + 2
                elif text.startswith("-/", i):
                    depth, i = depth - 1, i + 2
                else:
                    i += 1
            continue
        m = re.match(r"import[ \t]+([^\s]+)[^\n]*", text[i:])
        if not m:
            break
        line = text.count("\n", 0, i)
        imports.append((line, m.group(1), "shake: keep" in m.group(0)))
        i += m.end()
    return imports


IDENT = r"[A-Za-z_«][\w.'«»!?]*"


def logical_lines(text):
    """The lines of `text` without comments, an indented line joined to the `open`/`attribute`
    command it continues."""
    text = re.sub(r"/-.*?-/", lambda mo: "\n" * mo.group(0).count("\n"), text, flags=re.S)
    out = []
    for line in text.split("\n"):
        line = line.split("--")[0]
        if out and line[:1].isspace() and line.strip() and re.match(r"\s*(open|export|attribute)\b", out[-1]):
            out[-1] += " " + line.strip()
        else:
            out.append(line)
    return out


def scope_requirements(text, known):
    """For every `open`/`export` of the file: the names the opened namespace may resolve to (it
    is relative to the enclosing namespaces and to earlier `open`s; Lean fails with `unknown
    namespace` unless an imported module registers one of them). And for every name an
    `attribute [...] x y` command applies an attribute to, and every other identifier the file
    writes: the names it may resolve to (the module defining it must be imported: Lean records no
    use of a name a local attribute or a failed tactic alternative names).
    Returns (open requirements, attribute requirements), each a list of candidate-name sets."""
    scopes, opened, reqs, attrs = [], set(), [], []

    def candidates(i):
        cur = ".".join(n for k, n in scopes if k == "ns" and n)
        parts = cur.split(".") if cur else []
        prefixes = [""] + [".".join(parts[:k]) for k in range(1, len(parts) + 1)]
        if i.startswith("_root_."):
            cands = {i[len("_root_."):]}
        else:
            cands = {(p + "." + i) if p else i for p in prefixes} | {o + "." + i for o in opened}
        return {c.replace("«", "").replace("»", "") for c in cands}
    idents = []
    for line in logical_lines(text):
        m = re.match(r"\s*(namespace|section|end|open|export|noncomputable section|attribute)\b\s*(.*)", line)
        if not m:
            # every identifier the file writes: a tactic proof can name a lemma that its final
            # term does not mention (a `first` alternative that failed, an unused `simp` lemma),
            # and the file still needs it to elaborate
            body = re.sub(r'"(?:[^"\\]|\\.)*"', " ", line)
            for tok in set(re.findall(r"[A-Za-z_«][\w.'!?«»]*", body)):
                tok = tok.rstrip(".")
                if "." in tok or len(tok) > 3:
                    idents.append(candidates(tok))
        if not m:
            continue
        kw, rest = m.group(1), m.group(2).strip()
        if kw == "namespace":
            scopes.append(("ns", rest.split()[0] if rest else ""))
        elif kw in ("section", "noncomputable section"):
            scopes.append(("sec", rest.split()[0] if rest else ""))
        elif kw == "end":
            if scopes:
                scopes.pop()
        elif kw == "attribute":
            mo = re.match(r"\[(.*?)\]\s*(.*)", rest)
            if not mo:
                continue
            for tok in mo.group(2).split():
                if tok == "in":
                    break
                if re.fullmatch(IDENT, tok):
                    attrs.append(candidates(tok))
        else:
            rest = re.sub(r"^scoped\s+", "", rest)
            ids = []
            for tok in rest.split():
                if tok in ("in", "hiding", "renaming") or tok.startswith("("):
                    break
                if not re.fullmatch(IDENT, tok):
                    break
                ids.append(tok)
                if re.search(r"\s(hiding|renaming)\s|\(", rest):
                    break    # `open A hiding x`, `open A (x)`: only A is a namespace
            for i in ids:
                cands = candidates(i)
                reqs.append(cands)
                if not re.search(r"\sin\b", " " + rest):   # `open X in`: this command only
                    opened |= cands & known
            # names an `open X (a b)` / `open X in ...` command writes
            body = re.sub(r'"(?:[^"\\]|\\.)*"', " ", rest)
            for tok in set(re.findall(r"[A-Za-z_«][\w.'!?«»]*", body)):
                tok = tok.rstrip(".")
                if "." in tok or len(tok) > 3:
                    idents.append(candidates(tok) | {o + "." + tok for i in ids for o in candidates(i)})
    return reqs, attrs + idents


REALIZED = re.compile(r"(eq|match|proof|omega)_\d+|eq_def|eq_unfold|induct|induct_unfolding|fun_cases|"
                      r"mutual_induct|_unfold|_sunfold|sizeOf_spec|congr_simp|inj|injEq")


def import_conflicts(mods, cwd=ROOT, env=None):
    """Pairs of modules that define the same (non-auxiliary) constant name (scripts/shake/Names.lean);
    two such modules cannot be imported into one environment."""
    tmp = pathlib.Path(os.environ.get("TMPDIR") or "/tmp") / "shake/names"
    tmp.mkdir(parents=True, exist_ok=True)
    lst, out = tmp / "mods.txt", tmp / "names.tsv"
    lst.write_text("\n".join(mods) + "\n")
    cmd = ["lean", "--run"] if env else ["lake", "env", "lean", "--run"]
    subprocess.run(cmd + [str(ROOT / "scripts/shake/Names.lean"), str(out), str(lst)], cwd=cwd,
                   env=env, check=True)
    by = {}
    for line in out.read_text().splitlines():
        c, m = line.split("\t")
        parts = c.split(".")
        if REALIZED.fullmatch(parts[-1]) or any(x.startswith("_") for x in parts):
            continue
        by.setdefault(c, set()).add(m)
    pairs = set()
    for ms in by.values():
        ms = sorted(ms)
        for i, x in enumerate(ms):
            for y in ms[i + 1:]:
                pairs.add((x, y))
    return pairs


def source_closures(mods):
    """Internal import closures from the source files (other modules: themselves only)."""
    imps = {}
    for m in mods:
        p = mod_path(m) if internal(m) and m.count(".") and mod_path(m).exists() else None
        imps[m] = [x for _, x, _ in parse_header(p.read_text())] if p else []
    clos = {}

    def go(m):
        if m in clos:
            return clos[m]
        clos[m] = set()
        s = {m}
        for x in imps.get(m, ()):
            if internal(x) and x.count(".") and mod_path(x).exists():
                s |= go(x)
        clos[m] = s
        return s
    sys.setrecursionlimit(max(10000, sys.getrecursionlimit()))
    for m in mods:
        go(m)
    return clos


def lean_batches(script, mods, out, cwd=ROOT, env=None, tag="batch"):
    """Run `lean --run script <out> <list>` over `mods`, writing the concatenated output to `out`.
    Modules go into as few environments as possible: two modules whose import closures define the
    same name (`import_conflicts`) go into different ones; an unforeseen `already contains` failure
    splits a batch in halves."""
    tmp = pathlib.Path(out).with_suffix(".parts")
    tmp.mkdir(parents=True, exist_ok=True)
    parts, k = [], [0]
    cmd = ["lean", "--run", str(ROOT / script)] if env else ["lake", "env", "lean", "--run", str(ROOT / script)]

    lock = __import__("threading").Lock()

    def go(ms):
        with lock:
            k[0] += 1
            n = k[0]
        lst, o = tmp / f"{tag}{n}.txt", tmp / f"{tag}{n}.out"
        lst.write_text("\n".join(ms) + "\n")
        r = subprocess.run(cmd + [str(o), str(lst)], cwd=cwd, env=env, capture_output=True, text=True)
        if r.returncode == 0:
            parts.append(o)
            return
        err = r.stdout + r.stderr
        if "already contains" not in err or len(ms) == 1:
            sys.exit(f"{script} failed on {len(ms)} modules: {err[-2000:]}")
        h = len(ms) // 2
        go(ms[:h])
        go(ms[h:])
    groups = [sorted(mods)]
    if len(mods) > 1:
        pairs = import_conflicts(sorted(mods), cwd, env)
        if pairs:
            base = {m: m[len("ShakeX."):] if m.startswith("ShakeX.") else m for m in mods}
            bc = source_closures(sorted(set(base.values())))
            clos = {m: bc.get(base[m], set()) | {m, base[m]} for m in mods}
            for x, y in list(pairs):   # a shadow copy conflicts like its module
                for m in mods:
                    if base[m] != m and base[m] in (x, y):
                        pairs.add((m, y if base[m] == x else x))
            # names some module's closure holds twice are compatible (Lean accepts the duplicate)
            involved = {x for xy in pairs for x in xy}
            together = set()
            for m in mods:
                t = sorted(clos[m] & involved)
                for i, x in enumerate(t):
                    for y in t[i + 1:]:
                        together.add((x, y))
            pairs = {(x, y) for x, y in pairs if (min(x, y), max(x, y)) not in together}
            bad = {}
            for x, y in pairs:
                bad.setdefault(x, set()).add(y)
                bad.setdefault(y, set()).add(x)
            groups, tags, avoid = [], [], []
            for m in sorted(mods, key=lambda m: -len(clos.get(m, ()))):
                t = {x for x in clos.get(m, {m}) if x in bad}
                av = set().union(*(bad[x] for x in t)) if t else set()
                for i in range(len(groups)):
                    if not (t & avoid[i]) and not (av & tags[i]):
                        groups[i].append(m)
                        tags[i] |= t
                        avoid[i] |= av
                        break
                else:
                    groups.append([m])
                    tags.append(set(t))
                    avoid.append(set(av))
    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(int(os.environ.get("SHAKE_JOBS", "3"))) as ex:
        list(ex.map(lambda gm: go(sorted(gm)), groups))
    parts.sort(key=lambda p: int(re.sub(r"\D", "", p.stem) or 0))
    with open(out, "w") as f:
        for p in parts:
            f.write(p.read_text())
    return len(parts)


SYNTAX_DECL = re.compile(r"^[ \t]*(?:@\[[^\]]*\][ \t]*)?(?:(?:local|scoped)[ \t]+)?"
                         r"(?:syntax|macro|elab|notation|infixl|infixr|infix|prefix|postfix)\b", re.M)
WORD = re.compile(r"[A-Za-z_][\w!?']*")


def strip_comments(text):
    text = re.sub(r"/-.*?-/", " ", text, flags=re.S)
    return re.sub(r"--[^\n]*", " ", text)


def declared_atoms(text):
    """The string atoms of the syntax declarations (`syntax`, `macro`, `elab`, `notation`, `infix`,
    ...) of a file: identifier-like atoms (`"rule_auto_c "`) are not in Lean's token table, so a
    file that only parses them (a tactic in a `first` alternative that never runs) records no use
    of their module."""
    text = strip_comments(text)
    atoms = set()
    for mo in SYNTAX_DECL.finditer(text):
        end = len(text)
        for stop in ("=>", ":=", "\n\n"):
            k = text.find(stop, mo.end())
            if k >= 0:
                end = min(end, k)
        for lit in re.findall(r'"((?:[^"\\]|\\.)*)"', text[mo.end():end]):
            a = lit.strip()
            if a:
                atoms.add(a)
    return atoms


def used_words(text):
    """Identifier-like words and the text of a file outside comments and string literals."""
    t = strip_comments(text)
    t = re.sub(r'"(?:[^"\\\n]|\\.)*"', " ", t)
    return set(WORD.findall(t)), t


CONSUMER_FILES = ["scripts/audit/*.lean", "scripts/rust-clif/*.lean", "float-spec/defs-hash.lean"]
