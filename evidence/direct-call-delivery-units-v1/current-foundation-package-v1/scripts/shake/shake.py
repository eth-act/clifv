pinned = []   # import lists of unbuilt consumer files (consumer_facts)


def consumer_facts(tmp):
    """Facts of the Lean files outside FV/FVTest/Corpus that import them: the loose files of
    CONSUMER_FILES (compiled here as modules `ShakeC.*`, each `#print axioms X` turned into a
    theorem that mentions X) and the built packages of CONSUMER_PKGS. Returns
    ([facts files], {module: source text})."""
    root = tmp / "consumers"
    (root / "ShakeC").mkdir(parents=True, exist_ok=True)
    texts, names = {}, []
    lp = lake_lean_path()
    for pat in CONSUMER_FILES:
        for p in sorted(ROOT.glob(pat)):
            text = p.read_text()
            body, _ = shadow_text(text)
            body = body.replace("shakeEx_file_", f"shakeEx_{len(names)}_").replace(
                "shakeUse_file_", f"shakeUse_{len(names)}_").replace("shakeCmd_file_", f"shakeCmd_{len(names)}_")
            name = "ShakeC." + re.sub(r"\W", "_", str(p.relative_to(ROOT).with_suffix("")))
            src = root / (name.replace(".", "/") + ".lean")
            src.write_text(body)
            r = subprocess.run(["lean", "-R", str(root), "-o", str(src.with_suffix(".olean")), str(src)],
                               env={**os.environ, "LEAN_PATH": lp}, capture_output=True, text=True)
            if r.returncode != 0:
                # e.g. it imports a module that is not built: keep the old closures of its imports
                print(f"note: consumer {p.relative_to(ROOT)} does not compile here; the old closures "
                      f"of its imports are kept: " + " ".join((r.stdout + r.stderr).split())[:300],
                      file=sys.stderr)
                pinned.append([x for _, x, _ in parse_header(text) if internal(x)])
                continue
            names.append(name)
            texts[name] = text
    outs = []
    if names:
        out = tmp / "consumers.jsonl"
        lean_batches("scripts/shake/Facts.lean", names, out,
                     env={**os.environ, "LEAN_PATH": lp + ":" + str(root)}, tag="consumers")
        outs.append(out)
    for pkg, lib in CONSUMER_PKGS.items():
        if not (ROOT / pkg / ".lake/build/lib/lean" / lib).exists():
            # not built: every module of the old closure of its imports stays reachable
            for p in sorted((ROOT / pkg / lib).rglob("*.lean")):
                pinned.append([x for _, x, _ in parse_header(p.read_text()) if internal(x)])
            print(f"note: {pkg} is not built; the old closures of its imports are kept", file=sys.stderr)
            continue
        ms = []
        for p in sorted((ROOT / pkg / lib).rglob("*.lean")):
            m = ".".join(p.relative_to(ROOT / pkg).with_suffix("").parts)
            ms.append(m)
            texts[m] = p.read_text()
        out = tmp / f"{pkg}.jsonl"
        lean_batches("scripts/shake/Facts.lean", ms, out, cwd=ROOT / pkg, tag=pkg)
        outs.append(out)
    return outs, texts


SHADOW = re.compile(r"^(example|#guard|#eval|#check|#reduce|#print)(?=\s)", re.M)
SCOPE = re.compile(r"^(namespace|section|noncomputable section|end|open|variable|universe|set_option|"
                   r"local notation|local infix|local macro|local instance|attribute \[local)\b")


def shadow_text(text, module=None):
    """The `example`, `#guard`, `#eval`, `#check`, `#reduce` and `#print` commands of `text`
    (their elaboration is not in the .olean) turned into declarations, with the scope commands
    around them (namespace/section/end/open/variable/universe/set_option) and the private
    declarations (not visible from another module), after `import module`
    and the file's own imports; every other command is dropped (it is in `module`'s .olean).
    Without `module`, the whole file is kept (for files that are not modules)."""
    k = [0]
    tag = re.sub(r"\W", "_", module or "file")

    def decl(cmd):
        k[0] += 1
        kw = SHADOW.match(cmd).group(1)
        rest = cmd[len(kw):]
        if kw == "example":
            return f"noncomputable def shakeEx_{tag}_{k[0]}" + rest
        if kw in ("#print", "#check"):
            rest = re.sub(r"^\s*axioms\b", "", rest)
            return f"theorem shakeUse_{tag}_{k[0]} : True := let _ := @" + rest.strip() + "; trivial\n"
        if kw == "#guard":
            return f"noncomputable def shakeCmd_{tag}_{k[0]} : Bool := ({rest.rstrip()}\n  : Bool)\n"
        return f"noncomputable def shakeCmd_{tag}_{k[0]} :=" + rest
    hdr_end = 0
    for ln, _, _ in parse_header(text):
        hdr_end = ln + 1
    lines = text.split("\n")
    header = "\n".join(lines[:hdr_end])
    body = "\n".join(lines[hdr_end:])
    body = re.sub(r"/-.*?-/", lambda mo: "\n" * mo.group(0).count("\n"), body, flags=re.S)
    body = re.sub(r"--[^\n]*", "", body)
    # split into top-level commands: a command starts at a non-blank, non-comment column-0 line
    cmds, cur = [], []
    for ln in body.split("\n"):
        if ln and not ln[0].isspace() and not ln.startswith(("--", "|", ")", "]", "}", "·", "⟩")) and cur:
            cmds.append("\n".join(cur) + "\n")
            cur = []
        cur.append(ln)
    if cur:
        cmds.append("\n".join(cur) + "\n")
    out, in_mutual = [], False
    for c in cmds:
        if module is not None and re.match(r"mutual\b", c):
            in_mutual = True
            continue
        if in_mutual:
            in_mutual = not re.match(r"end\b", c)
            continue
        c = re.sub(r"^#guard_msgs\b[^\n]*?\bin\b\s*", "", c)
        lead = []
        while True:   # `set_option x in` / `open X in` prefixes
            mo = re.match(r"((?:set_option|open)\b[^\n]*?\bin)\b[ \t]*\n?", c)
            if not mo:
                break
            lead.append(mo.group(1))
            c = c[mo.end():]
        if module is None:
            out.append(" ".join(lead + [""]) + (decl(c) if SHADOW.match(c) else c))
        elif SHADOW.match(c):
            out.append(" ".join(lead + [""]) + decl(c))
        elif SCOPE.match(c) and not lead:
            out.append(c)
        elif re.match(r"(@\[[^\]]*\]\s*)?private\b", c):
            # private names of `module` are not visible from the copy
            out.append(" ".join(lead + [""]) + c)
    imports = header + (f"\nimport {module}" if module else "")
    return imports + "\n" + "".join(out), k[0]


def shadow_facts(tmp, mods, lp):
    """Facts of shadow copies (scripts `shadow_text`) of the modules with such commands, compiled
    here as `ShakeX.<module>`. Returns (facts file or None, {module: problem})."""
    root = tmp / "shadow"
    failed, names = {}, []
    jobs = []
    for m in mods:
        text = mod_path(m).read_text()
        if not SHADOW.search(text):
            continue
        body, n = shadow_text(text, m)
        src = root / "ShakeX" / (m.replace(".", "/") + ".lean")
        src.parent.mkdir(parents=True, exist_ok=True)
        olean = src.with_suffix(".olean")
        mo = (ROOT / ".lake/build/lib/lean" / (m.replace(".", "/") + ".olean"))
        if (src.exists() and src.read_text() == body and olean.exists() and mo.exists()
                and olean.stat().st_mtime > mo.stat().st_mtime):
            names.append("ShakeX." + m)   # unchanged since the last run
            continue
        src.write_text(body)
        olean.unlink(missing_ok=True)
        jobs.append((m, src))

    def run(job):
        m, src = job
        r = subprocess.run(["lean", "-R", str(root), "-Dlinter.all=false", "-o",
                            str(src.with_suffix(".olean")), str(src)],
                           env={**os.environ, "LEAN_PATH": lp}, capture_output=True, text=True)
        out = r.stdout + r.stderr
        errs = [l for l in out.splitlines() if ": error" in l]
        return m, r.returncode, (errs[0] if errs else out[-300:])
    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(int(os.environ.get("SHAKE_JOBS", "6"))) as ex:
        for m, rc, out in ex.map(run, jobs):
            if rc:
                failed[m] = "shadow copy does not compile: " + " ".join(out.split())[-200:]
            else:
                names.append("ShakeX." + m)
    if not names:
        return None, failed
    out = tmp / "shadow.jsonl"
    lean_batches("scripts/shake/Facts.lean", names, out, env={**os.environ, "LEAN_PATH": lp + ":" + str(root)},
                 tag="shadow")
    return out, failed


def open_pr_files(ignore=()):
    """Files changed by open, non-draft pull requests (vs. their merge base with origin/main).
    Draft PRs (parked prototypes, e.g. a whole-tree port) and the PRs in `ignore` are not counted."""
    try:
        r = subprocess.run(["gh", "pr", "list", "--state", "open", "--limit", "500", "--json",
                            "number,isDraft"], cwd=ROOT, capture_output=True, text=True, check=True)
        prs = [(p["number"], p["isDraft"]) for p in json.loads(r.stdout)]
    except (OSError, subprocess.CalledProcessError):
        url = "https://api.github.com/repos/eth-act/clifv/pulls?state=open&per_page=100"
        out = subprocess.run(["curl", "-sf", url], capture_output=True, text=True, check=True).stdout
        prs = [(p["number"], p["draft"]) for p in json.loads(out)]
    nums = [n for n, draft in prs if not draft and n not in ignore]
    print(f"open PRs counted: {nums}; skipped (draft or --ignore-pr): "
          f"{[n for n, d in prs if n not in nums]}", file=sys.stderr)
    files = {}
    if not nums:
        return files
    subprocess.run(["git", "fetch", "-q", "origin", "main"] +
                   [f"+refs/pull/{n}/head:refs/shake-pr/{n}" for n in nums], cwd=ROOT, check=True)
    for n in nums:
        base = subprocess.run(["git", "merge-base", "origin/main", f"refs/shake-pr/{n}"], cwd=ROOT,
                              capture_output=True, text=True).stdout.strip()
        if not base:
            continue
        diff = subprocess.run(["git", "diff", "--name-only", base, f"refs/shake-pr/{n}"], cwd=ROOT,
                              capture_output=True, text=True, check=True).stdout.split()
        for f in diff:
            files.setdefault(f, []).append(n)
    return files


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--facts", help="reuse a Facts.lean output instead of running it")
    ap.add_argument("--no-pr-skip", action="store_true")
    ap.add_argument("--ignore-pr", type=int, action="append", default=[],
                    help="do not skip the files of this open PR")
    ap.add_argument("--dry-run", action="store_true", help="report, do not edit")
    ap.add_argument("--report", default=None, help="write the per-file edits (JSON) here")
    ap.add_argument("--edit-generated", action="store_true",
                    help="also edit generated files (to see what their generators should emit)")
    ap.add_argument("--no-consumers", action="store_true",
                    help="do not protect the files outside FV/FVTest/Corpus that import them")
    ap.add_argument("--no-shadow", action="store_true",
                    help="do not re-elaborate example/#guard/#eval commands (see shadow_text)")
    ap.add_argument("--simp-default", action="store_true",
                    help="also keep the contributors of Lean's default simp set (see simp_need)")
    ap.add_argument("--unbuilt-frozen", action="store_true",
                    help="analyse only built modules; the others keep their imports and their old closures")
    ap.add_argument("--only", help="file listing the modules to analyse (an import-closed subset)")
    a = ap.parse_args()
    os.chdir(ROOT)

    mods = all_modules()
    if a.only:
        mods = pathlib.Path(a.only).read_text().split()
    tmp = pathlib.Path(os.environ.get("TMPDIR") or "/tmp") / "shake"
    tmp.mkdir(exist_ok=True)
    facts_path = a.facts
    if not facts_path:
        facts_path = str(tmp / "facts.jsonl")
        fm = mods
        if a.unbuilt_frozen:
            fm = [m for m in mods if (ROOT / ".lake/build/lib/lean" / (m.replace(".", "/") + ".olean")).exists()]
        n = lean_batches("scripts/shake/Facts.lean", fm, facts_path, tag="facts")
        print(f"facts: {len(fm)} modules in {n} environments")
    cons_files, cons_text = ([], {}) if a.no_consumers else consumer_facts(tmp)
    facts, graph, ns, tokens, simpsets = {}, {}, {}, {}, {}
    for line in (l for f in [facts_path, *cons_files] for l in open(f)):
        d = json.loads(line)
        ns[d.get("g") or d["m"]] = d.get("ns", [])
        tokens[d.get("g") or d["m"]] = d.get("tokens", [])
        simpsets[d.get("g") or d["m"]] = d.get("simpsets", [])
        if "g" in d:
            graph[d["g"]] = d["imports"]
        else:
            facts[d["m"]] = d
            graph[d["m"]] = d["imports"]
    missing = [m for m in mods if m not in facts]
    if missing and not a.unbuilt_frozen:
        sys.exit(f"no facts for {len(missing)} modules (not built?): {missing[:5]}")
    for m in missing:   # --unbuilt-frozen: kept as they are, with their whole old closure
        pinned.append([x for _, x, _ in parse_header(mod_path(m).read_text()) if internal(x)])
    mods = [m for m in mods if m in facts]
    shadow_bad = {}
    if not a.no_shadow:
        sf, shadow_bad = shadow_facts(tmp, mods, lake_lean_path())
        for line in (open(sf) if sf else ()):
            d = json.loads(line)
            if "m" not in d:
                continue
            m = d["m"][len("ShakeX."):]
            for key in ("needs", "extra", "indirect", "quoted"):
                facts[m][key] = sorted(set(facts[m][key]) | {x for x in d[key] if x != m})

    # topological order of every module, bitset closures
    order, seen = [], set()

    def visit(m):
        stack = [(m, iter(graph.get(m, ())))]
        seen.add(m)
        while stack:
            x, it = stack[-1]
            for y in it:
                if y not in seen:
                    seen.add(y)
                    stack.append((y, iter(graph.get(y, ()))))
                    break
            else:
                order.append(x)
                stack.pop()
    for m in sorted(graph):
        if m not in seen:
            visit(m)
    idx = {m: k for k, m in enumerate(order)}
    bit = {m: 1 << k for m, k in idx.items()}

    def bits(names):
        b = 0
        for x in names:
            b |= bit[x]
        return b

    def members(b):
        out = []
        while b:
            low = b & -b
            out.append(order[low.bit_length() - 1])
            b ^= low
        return out

    orig_T = {}
    for m in order:
        t = 0
        for y in graph.get(m, ()):
            t |= bit[y] | orig_T[y]
        orig_T[m] = t

    pr_files = {} if a.no_pr_skip else open_pr_files(set(a.ignore_pr))
    gen_ok = set()
    gl = ROOT / "scripts/shake/generated.txt"
    if gl.exists():
        gen_ok = {l.split("#")[0].strip() for l in gl.read_text().splitlines()} - {""}
    gen_keep = {x[len("keep:"):].strip() for x in gen_ok if x.startswith("keep:")}
    gen_ok -= {x for x in gen_ok if x.startswith("keep:")}

    headers, frozen = {}, {}
    for m in mods:
        p = mod_path(m)
        text = p.read_text()
        headers[m] = parse_header(text)
        rel = str(p.relative_to(ROOT))
        if "shake: keep-all" in text or rel in gen_keep:
            frozen[m] = "keep-all"
        elif facts[m]["nconsts"] == 0:
            frozen[m] = "no constants"
        elif m in shadow_bad:
            frozen[m] = "examples not analysed (" + shadow_bad[m] + ")"
        elif rel in pr_files:
            frozen[m] = "open PR " + ",".join(f"#{n}" for n in pr_files[rel])
        elif (gen := generator_of(text, rel)) and gen not in gen_ok and not a.edit_generated:
            frozen[m] = f"generated ({gen})"
        src = [x for _, x, _ in headers[m]]
        oimp = [x for x in graph[m] if x != "Init"]
        if sorted(set(src)) != sorted(set(oimp)):
            sys.exit(f"{m}: source imports {src} differ from the .olean's {oimp} (rebuild first)")

    providers = {}
    for m, names in ns.items():
        for n in names:
            providers[n] = providers.get(n, 0) | bit[m]
    known = set(providers)
    scopes_req = {m: scope_requirements(mod_path(m).read_text(), known) for m in mods}
    opens = {m: r[0] for m, r in scopes_req.items()}
    attr_req = {m: r[1] for m, r in scopes_req.items()}
    consumers = [m for m in cons_text if m in facts]
    for m in consumers:
        frozen[m] = "consumer"
        opens[m], attr_req[m] = scope_requirements(cons_text[m], known)

    # syntax: modules whose declared atoms or tokens a file uses (see declared_atoms)
    ext_tokens = {t.strip() for x, f in tokens.items() if not internal(x) for t in f}
    atom_mods = {}
    for x in mods:
        toks = declared_atoms(mod_path(x).read_text()) | {t.strip() for t in tokens.get(x, ())}
        for t in toks - ext_tokens:
            if t:
                atom_mods[t] = atom_mods.get(t, 0) | bit[x]
    word_atoms = {t: b for t, b in atom_mods.items() if WORD.fullmatch(t)}
    sym_atoms = {t: b for t, b in atom_mods.items() if not WORD.fullmatch(t)}
    syn_need = {}
    for m in list(facts):
        text = cons_text[m] if m in cons_text else (mod_path(m).read_text() if m in headers else None)
        if text is None:
            continue
        words, body = used_words(text)
        b = 0
        for w in words & word_atoms.keys():
            b |= word_atoms[w]
        for t, tb in sym_atoms.items():
            if tb & orig_T[m] and t in body:
                b |= tb
        syn_need[m] = b & orig_T[m]

    # simp sets: a module that uses a simp set keeps the modules of its old closure that add
    # lemmas to it (the default set only with --simp-default)
    def set_decl(e):
        parts = e[len("ext._@."):].split(".")
        k = next((i for i, x in enumerate(parts) if x.isdigit()), len(parts))
        return ".".join(parts[:k])
    contrib = {}
    for x, sets in simpsets.items():
        for e in sets:
            if x in bit:
                contrib[e] = contrib.get(e, 0) | bit[x]
    sets_of_decl = {}
    for e in contrib:
        if e.startswith("ext._@."):
            sets_of_decl.setdefault(set_decl(e), []).append(e)
    simp_need = {}
    for m in facts:
        b = 0
        for dm in set(facts[m]["extra"]) & sets_of_decl.keys():
            for e in sets_of_decl[dm]:
                b |= contrib[e]
        if a.simp_default and "Lean.Meta.simpExtension" in contrib:
            text = cons_text[m] if m in cons_text else (mod_path(m).read_text() if m in headers else "")
            if re.search(r"\bsimp", strip_comments(text)):
                b |= contrib["Lean.Meta.simpExtension"]
        simp_need[m] = b & orig_T[m]

    # `attribute [...] x`: the module defining x (the lowest one of the old closure, if several)
    want_names = {c for reqs in attr_req.values() for cands in reqs for c in cands}
    owners = {}
    if want_names:
        nt = tmp / "names-all.tsv"
        lst = tmp / "names-all.txt"
        lst.write_text("\n".join(x for x in order if internal(x) and x in facts) + "\n")
        subprocess.run(["lake", "env", "lean", "--run", str(ROOT / "scripts/shake/Names.lean"), str(nt),
                        str(lst), "all"], cwd=ROOT, check=True)
        for line in open(nt):
            c, x = line.rstrip("\n").split("\t")
            if c in want_names and x in bit:
                owners[c] = owners.get(c, 0) | bit[x]
    attr_need = {}
    for m, reqs in attr_req.items():
        b = 0
        for cands in reqs:
            for c in sorted(cands, key=len, reverse=True):
                o = owners.get(c, 0) & (orig_T.get(m, 0) | bit.get(m, 0))
                if o:
                    b |= o & -o if not (o & bit.get(m, 0)) else 0
                    break
        attr_need[m] = b

    rev = [m for m in mods if facts[m]["rev"]]
    rev_b = bits(rev)
    # external modules imported directly by some internal module (umbrella candidates)
    ext_direct = {m: [x for x in graph[m] if not internal(x) and x != "Init"] for m in mods}

    def needs_of(m):
        f = facts[m]
        need = bits(f["needs"]) | bits(set(f["extra"])) | bits(x for x in f.get("quoted", ()) if x in bit)
        need |= bits(f["indirect"]) & orig_T[m]
        need |= rev_b & orig_T[m]
        need |= syn_need.get(m, 0) | simp_need.get(m, 0) | attr_need.get(m, 0)
        return need & ~bit[m]

    def frozen_needs(m):
        """needs_of(m), and for every `open` its needs do not provide: the lowest module of the
        old closure that registers the namespace."""
        need = needs_of(m)
        C = need | bit[m]
        for x in members(need):
            C |= T0[x]
        for cands in opens.get(m, ()):
            prov = [providers.get(c, 0) for c in cands]
            if not any(p & C for p in prov):
                old = [p & orig_T[m] for p in prov if p & orig_T[m]]
                if old:
                    k = min((p & -p).bit_length() - 1 for p in old)
                    need |= 1 << k
                    C |= (1 << k) | T0[order[k]]
        return need

    T0 = orig_T
    fneeds = {m: frozen_needs(m) for m in frozen}
    for k, imps in enumerate(pinned):
        name = f"<consumer {k}>"
        graph[name] = imps
        b = 0
        for x in imps:
            if x in bit:
                b |= bit[x] | orig_T[x]
        frozen[name], fneeds[name] = "consumer", b
    forced = set()   # (importer, import) removals that would break a frozen module

    pos_memo = {}

    def old_pos(m):
        """Load position of every module in m's old environment (depth-first, in import order)."""
        if m not in pos_memo:
            pos, seen = {}, set()
            stack = [(x, False) for x in reversed(graph[m])]
            while stack:
                x, done = stack.pop()
                if done:
                    pos[x] = len(pos)
                    continue
                if x in seen:
                    continue
                seen.add(x)
                stack.append((x, True))
                stack.extend((y, False) for y in reversed(graph.get(x, ())))
            pos_memo[m] = pos
        return pos_memo[m]

    def solve():
        T = dict(orig_T)
        imports, edits = {}, {}
        for m in order:
            if m not in facts:
                continue
            old = graph[m]
            if m in frozen:
                new = list(old)
            else:
                hdr = headers[m]
                keep = bits(x for _, x, k in hdr if k)
                keep |= bits(x for x in old if not internal(x) or x.startswith(m + ".")
                             or (m, x) in forced)
                deps = needs_of(m) | keep
                red = 0
                for x in members(deps):
                    red |= T[x]
                # `open X` needs a module registering X: the lowest one of the old closure
                C = deps | red | bit[m]
                for cands in opens[m]:
                    prov = [providers.get(c, 0) for c in cands]
                    if any(p & C for p in prov):
                        continue
                    old_prov = [p & orig_T[m] for p in prov if p & orig_T[m]]
                    if old_prov:
                        k = min((p & -p).bit_length() - 1 for p in old_prov)
                        deps |= 1 << k
                        red |= T[order[k]]
                        C |= (1 << k) | T[order[k]]
                deps &= ~red
                deps |= keep
                kept = [x for x in old if bit[x] & deps]
                newT = 0
                for x in kept:
                    newT |= bit[x] | T[x]
                # an umbrella import (a module without constants) stays if every module it
                # imports is needed, or if replacing it would take more than UMBRELLA imports
                R = 0
                for x in members(deps):
                    R |= bit[x] | T[x]
                for u in old:
                    if u in facts and facts[u]["nconsts"] == 0 and not bit[u] & newT:
                        sub = deps & T[u] & ~newT
                        whole = not (bits(graph[u]) & ~R)   # every part of it is needed anyway
                        if bin(sub).count("1") > UMBRELLA or (sub and whole):
                            kept.append(u)
                            deps |= bit[u]
                            newT |= bit[u] | T[u]
                add = []
                for x in sorted(members(deps), key=idx.get, reverse=True):
                    if not (newT & bit[x]):
                        y = x
                        if not internal(x):
                            cands = {e for q in [m] + [q for q in members(orig_T[m]) if q in facts]
                                     for e in ext_direct[q] if bit[x] & (bit[e] | T[e])}
                            y = min(cands, key=lambda e: (len(e.split(".")), e)) if cands else x
                        if y not in old and y not in add:
                            add.append(y)
                        newT |= bit[y] | T[y]
                keep_l = [x for x in old if bit[x] & deps or bit[x] & newT]
                # Lean loads a module's imports depth-first in import order, and later modules
                # take precedence (simp lemmas, macro_rules alternatives, instances): an added
                # import goes before the first kept import that the old environment loaded after
                # it, so that it loads at about the same point as before
                pos = old_pos(m)
                new = list(keep_l)
                anchors = {}
                add.sort(key=lambda y: pos.get(y, 1 << 30))   # (the order the file gets them in)
                for y in add:
                    at = next((x for x in keep_l if pos.get(x, 0) > pos.get(y, 1 << 30)), None)
                    anchors[y] = at
                    new.insert(new.index(at) if at else len(new), y)
                removed = [x for x in old if x not in new]
                if removed or add:
                    edits[m] = (removed, [(y, anchors[y]) for y in add])
            t = 0
            for y in new:
                t |= bit[y] | T[y]
            T[m] = t
            imports[m] = new
        return T, imports, edits

    while True:
        T, imports, edits = solve()
        for name in (n for n in frozen if n.startswith("<consumer")):
            T[name] = 0
            for y in graph[name]:
                if y in bit:
                    T[name] |= bit[y] | T[y]
        # frozen modules must still reach everything they need
        broken = [(m, fneeds[m] & ~T[m]) for m in frozen if fneeds[m] & ~T[m]]
        if not broken:
            break
        new_forced = set()
        for m, miss in broken:
            for target in members(miss):
                # cheapest path to `target` over current edges (cost 0) and removed ones (cost 1)
                dist, prev = {m: 0}, {}
                dq = [(0, m)]
                while dq:
                    d, x = heapq.heappop(dq)
                    if x == target:
                        break
                    if d > dist[x]:
                        continue
                    for y in graph.get(x, ()):
                        if y not in bit or not (orig_T[y] & bit[target] or y == target):
                            continue
                        c = 0 if y in imports.get(x, graph[x]) else 1
                        if d + c < dist.get(y, 1 << 30):
                            dist[y], prev[y] = d + c, x
                            heapq.heappush(dq, (d + c, y))
                y = target
                while y != m:
                    x = prev[y]
                    if y not in imports.get(x, graph[x]):
                        new_forced.add((x, y))
                    y = x
        if not new_forced - forced:
            sys.exit(f"cannot repair frozen modules: {broken[:3]}")
        forced |= new_forced

    # load-order check: two modules adding entries under the same order key (Facts.lean,
    # `orderKeysOf`) must load in the same relative order as before in every module
    okeys = {m: facts[m].get("orderkeys", []) for m in mods}
    keyed = {m for m in mods if okeys[m]}

    def load_order(imps, m):
        out, seen = [], set()
        stack = [(x, False) for x in reversed(imps.get(m, graph.get(m, ())))]
        while stack:
            x, done = stack.pop()
            if done:
                if x in keyed:
                    out.append(x)
                continue
            if x in seen:
                continue
            seen.add(x)
            stack.append((x, True))
            stack.extend((y, False) for y in reversed(imps.get(x, graph.get(x, ()))))
        return out
    def flips_of(m):
        """(flipped order keys, the modules adding entries under them, in old load order)."""
        new_o = load_order(imports, m)
        old_o = load_order({}, m)
        if new_o == [x for x in old_o if x in set(new_o)]:
            return [], []
        rank_old = {x: k for k, x in enumerate(old_o)}
        extra_mods = [x for x in new_o if x not in rank_old]
        if extra_mods:
            sys.exit(f"{m}: new closure has modules the old one does not: {extra_mods[:5]}")
        bykey = {}
        for x in new_o:
            for k in okeys[x]:
                bykey.setdefault(k, []).append(x)
        flips = [k for k, xs in bykey.items() if [rank_old[x] for x in xs] != sorted(rank_old[x] for x in xs)]
        provs = sorted({x for k in flips for x in bykey[k]}, key=rank_old.get)
        return flips, provs

    # Repair: Lean takes the last-loaded of two equal-priority instances (simp lemmas, ...), so a
    # module whose new import lists load two such modules in the other order elaborates
    # differently (e.g. another `LawfulBEq Reg` instance in a definition's value). Such a module
    # imports, first and in their old load order, every module adding entries under a flipped
    # key except the last one: they are in its closure already, so its closure is unchanged, and
    # they now load before the rest. Modules are repaired in import order, so importers see it.
    reordered = set()
    for m in order:
        if m not in facts or m in frozen:
            continue
        for _ in range(8):
            flips, provs = flips_of(m)
            if not flips:
                break
            front = [x for x in provs[:-1] if internal(x)]
            if imports[m][:len(front)] == front:
                break
            imports[m] = front + [x for x in imports[m] if x not in front]
            reordered.add(m)
    for m in reordered:
        edits[m] = ([x for x in graph[m] if x not in imports[m]],
                    [(y, None) for y in imports[m] if y not in graph[m]])
    order_bad = {}
    for m in mods:
        if m in frozen and not graph[m]:
            continue
        flips, _ = flips_of(m)
        if flips:
            order_bad[m] = flips

    # report
    int_edges = lambda imps: sum(1 for m in mods for x in imps[m] if internal(x))
    before = int_edges(graph)
    after = int_edges(imports)
    removed = sum(len(r) for r, _ in edits.values())
    added = sum(len(ad) for _, ad in edits.values())
    reach_before = sum(bin(orig_T[m] & bits(mods)).count("1") for m in mods)
    reach_after = sum(bin(T[m] & bits(mods)).count("1") for m in mods)
    froz = {}
    for m, why in frozen.items():
        froz[why.split(" (")[0].split(" #")[0]] = froz.get(why.split(" (")[0].split(" #")[0], 0) + 1
    print(f"modules {len(mods)}, edited {len(edits)}; imports removed {removed}, added {added}; "
          f"internal import edges {before} -> {after}; internal reachable pairs "
          f"{reach_before} -> {reach_after}; consumers {len(consumers)}; "
          f"kept to protect frozen files {len(forced)}; load-order changes {len(order_bad)}; "
          f"frozen: {froz}")
    if a.report:
        pathlib.Path(a.report).write_text(json.dumps(
            {"edits": {m: {"remove": r, "add": [y for y, _ in ad], "before": {y: at for y, at in ad}}
                       for m, (r, ad) in sorted(edits.items())},
             "frozen": frozen, "forced": sorted(forced), "order": order_bad}, indent=1))
    if a.dry_run:
        return
    for m, (rm, add) in edits.items():
        p = mod_path(m)
        lines = p.read_text().split("\n")
        hdr = headers[m]
        if m in reordered:
            # the import lines, in the new order, in the slots of the old import lines
            text = {x: lines[ln] for ln, x, _ in hdr}
            # (graph[m] has the implicit `Init` import too, which has no line)
            new = [text.get(y, f"import {y}") for y in imports[m] if y in text or y not in graph[m]]
            slots = [ln for ln, _, _ in hdr]
            out = []
            for k, ln in enumerate(lines):
                if k in slots:
                    i = slots.index(k)
                    if i < len(new):
                        out.append(new[i])
                    if k == slots[-1]:
                        out.extend(new[len(slots):])
                    continue
                out.append(ln)
            p.write_text("\n".join(out))
            continue
        drop = {ln for ln, x, _ in hdr if x in rm}
        line_of = {x: ln for ln, x, _ in hdr}
        last = max((ln for ln, _, _ in hdr), default=-1)
        before = {}
        for y, at in add:
            before.setdefault(line_of[at] if at else None, []).append(f"import {y}")
        out = before.get(None, []) if last < 0 else []
        for k, ln in enumerate(lines):
            out.extend(before.get(k, []))
            if k not in drop:
                out.append(ln)
            if k == last:
                out.extend(before.get(None, []))
        p.write_text("\n".join(out))


